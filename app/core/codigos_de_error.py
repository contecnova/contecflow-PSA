def _serializables(params: dict) -> dict:
    """Los datos viajan en el JSON de la respuesta: lo que no sea texto, numero
    o booleano (un UUID, una fecha, un Enum...) va como texto (19-11-2026)."""
    return {k: v if v is None or isinstance(v, (str, int, float, bool)) else str(v) for k, v in params.items()}


