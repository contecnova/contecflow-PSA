def etiquetas(idioma: Optional[str]) -> dict[str, str]:
    """Las etiquetas de la factura en `idioma` (castellano para lo que falte)."""
    from app.services.traduccion.idiomas import normalizar
    return {**ETIQUETAS[IDIOMA_DE_RESPALDO], **ETIQUETAS.get(normalizar(idioma) or IDIOMA_DE_RESPALDO, {})}


def nombre_del_impuesto(db, org_id: Optional[str], idioma: Optional[str]) -> str:
    """El impuesto de la empresa (ajuste `TAX_NAME`) o, si esta vacio, el habitual del idioma."""
    if db is not None:
        try:
            from app.services.settings_service import get_runtime_str
            propio = (get_runtime_str(db, "TAX_NAME", org_id) or "").strip()
            if propio:
                return propio
        except Exception:
            logger.debug("nombre_del_impuesto: ajuste no legible", exc_info=True)
    return etiquetas(idioma)["impuesto"]


def idioma_de_la_factura(db, inv, org_id: Optional[str] = None) -> str:
    """El del cliente (idioma de su portal) y, si no, el de la empresa."""
    from app.services.formato_regional import idioma_de_salida
    preferido = None
    client_id = getattr(inv, "client_id", None)
    if db is not None and client_id:
        try:
            from app.models.clients import ClientPortalConfig
            preferido = db.query(ClientPortalConfig.default_language).filter(
                ClientPortalConfig.client_id == client_id).scalar()
        except Exception:
            logger.debug("idioma_de_la_factura: portal no legible", exc_info=True)
    return idioma_de_salida(db, org_id=org_id, preferido=preferido)


def _importe(valor, etiqueta: str) -> str:
    """Importe con la etiqueta de la moneda (su símbolo de `CURRENCY_SYMBOLS`, o su código: «1.234,00 CHF»)."""
    return f"{valor:,.2f} {etiqueta}"


def _fecha(d, idioma: Optional[str] = None) -> str:
    """Fecha en el formato del idioma (castellano por defecto), o una raya si no hay.

    La raya y no «None»: es un documento que se manda al cliente.
    """
    from app.services.formato_regional import formatear_fecha
    if d is None:
        return "—"
    if isinstance(d, (date, datetime)):
        return formatear_fecha(d, idioma or IDIOMA_DE_RESPALDO)
    return str(d)


# ── Fuentes y escape (auditoría 22-11-2026, A52 y A53) ────────────────────────
#
# Helvetica (WinAnsi) no tiene glifos chinos ni las letras polacas (ą, ę, ś, ż…):
# la factura china o polaca salía ilegible. Ahora: chino → STSong-Light (CID
# estándar, sin ficheros); el resto → DejaVu Sans (`app/assets/fonts`, licencia
# libre, cubre latín extendido, griego y cirílico); si faltara el fichero,
# Helvetica. Y todo texto que viene de datos va escapado (`R&D` o `<` daban 500).

_DIR_FUENTES = __import__("pathlib").Path(__file__).resolve().parents[1] / "assets" / "fonts"
_FUENTE_CJK = "STSong-Light"


def _fuentes(idioma: Optional[str]) -> tuple[str, str]:
    """(normal, negrita) registradas para el idioma de la factura."""
    from reportlab.pdfbase import pdfmetrics
    registradas = pdfmetrics.getRegisteredFontNames()
    if (idioma or "").lower().startswith("zh"):
        if _FUENTE_CJK not in registradas:
            from reportlab.pdfbase.cidfonts import UnicodeCIDFont
            pdfmetrics.registerFont(UnicodeCIDFont(_FUENTE_CJK))
        return _FUENTE_CJK, _FUENTE_CJK
    normal, negrita = _DIR_FUENTES / "DejaVuSans.ttf", _DIR_FUENTES / "DejaVuSans-Bold.ttf"
    if not (normal.exists() and negrita.exists()):
        logger.warning("invoice_pdf: sin DejaVu en %s; Helvetica (sin letras fuera de Latin-1)", _DIR_FUENTES)
        return "Helvetica", "Helvetica-Bold"
    if "DejaVuSans" not in registradas:
        from reportlab.pdfbase.ttfonts import TTFont
        pdfmetrics.registerFont(TTFont("DejaVuSans", str(normal)))
        pdfmetrics.registerFont(TTFont("DejaVuSans-Bold", str(negrita)))
    return "DejaVuSans", "DejaVuSans-Bold"


def _esc(texto) -> str:
    """Texto de datos para un `Paragraph` (XML de ReportLab): escapado y con saltos de línea."""
    from xml.sax.saxutils import escape
    return escape("" if texto is None else str(texto)).replace("\n", "<br/>")


def _estilos_de_factura(paleta, idioma: Optional[str] = None):
    """Los estilos del documento. `PS` acorta la construccion repetida."""
    hoja = getSampleStyleSheet()
    fn, fb = _fuentes(idioma)
    principal = paleta.color("texto_principal")
    secundario = paleta.color("texto_secundario")

    def PS(name, **kw):
        return ParagraphStyle(name, parent=hoja["Normal"], **kw)

    return {
        "PS": PS,
        "fn": fn,
        "fb": fb,
        "marca": PS("Brand", fontSize=16, fontName=fb,
                    textColor=paleta.color("acento"), spaceAfter=2),
        "h1": PS("H1", fontSize=22, fontName=fb,
                 textColor=principal, spaceAfter=4, leading=28),
        "etiqueta": PS("Lbl", fontSize=8, fontName=fb,
                       textColor=secundario, spaceAfter=1, textTransform="uppercase"),
        "cuerpo": PS("Body", fontSize=10, fontName=fn,
                     textColor=principal, spaceAfter=3, leading=14),
        "pequeno": PS("Small", fontSize=8, fontName=fn, textColor=secundario),
        "nota": PS("Note", fontSize=9, fontName=fn,
                   textColor=secundario, leading=13),
        "nombre_cliente": PS("ClientName", fontSize=12, fontName=fb,
                             textColor=principal, spaceAfter=2),
        "pie": PS("Footer", fontSize=7.5, fontName=fn,
                  textColor=secundario, alignment=TA_CENTER),
    }


def _cabecera_de_factura(company_name: str, est: dict, paleta) -> list:
    tabla = Table(
        [[Paragraph(_esc(company_name), est["marca"]), Paragraph(est["et"]["factura"], est["h1"])]],
        colWidths=[9 * cm, 8 * cm],
    )
    tabla.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, 0), "RIGHT"),
    ]))
    return [
        tabla,
        HRFlowable(width="100%", thickness=1.5, color=paleta.color("acento"),
                   spaceAfter=10, spaceBefore=6),
    ]


def _metadatos(invoice_number, issue_date, due_date, po_reference,
               period_from, period_to, est: dict) -> list:
    """Los datos identificativos. Los opcionales solo aparecen si vienen."""
    et, idioma = est["et"], est["idioma"]
    filas = [
        (et["numero"], invoice_number),
        (et["emision"], _fecha(issue_date, idioma)),
        (et["vencimiento"], _fecha(due_date, idioma)),
    ]
    if po_reference:
        filas.append((et["po"], po_reference))
    if period_from or period_to:
        filas.append((et["periodo"], f"{_fecha(period_from, idioma)} — {_fecha(period_to, idioma)}"))

    tabla = Table(
        [[Paragraph(k, est["etiqueta"]), Paragraph(_esc(v), est["cuerpo"])] for k, v in filas],
        colWidths=[4.5 * cm, 12.5 * cm],
    )
    tabla.setStyle(TableStyle([
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    return [tabla, Spacer(1, 14)]


def _bloque_de_emisor(emisor: Optional[dict], est: dict) -> list:
    """Datos fiscales del emisor (auditoría 22-11-2026, A54): razón social, NIF,
    domicilio e IBAN (ajustes `INVOICE_ISSUER_*` de la empresa). Sin ellos la
    factura no es válida (RD 1619/2012, art. 6)."""
    if not emisor or not any(emisor.values()):
        return []
    et = est["et"]
    salida = [Paragraph(et["emisor"], est["etiqueta"])]
    if emisor.get("nombre"):
        salida.append(Paragraph(_esc(emisor["nombre"]), est["nombre_cliente"]))
    if emisor.get("direccion"):
        salida.append(Paragraph(_esc(emisor["direccion"]), est["cuerpo"]))
    if emisor.get("nif"):
        salida.append(Paragraph(f"{et['nif']}: {_esc(emisor['nif'])}", est["pequeno"]))
    if emisor.get("iban"):
        salida.append(Paragraph(f"IBAN: {_esc(emisor['iban'])}", est["pequeno"]))
    salida.append(Spacer(1, 10))
    return salida


def datos_del_emisor(db, org_id: Optional[str]) -> dict:
    """Los ajustes `INVOICE_ISSUER_*` de la empresa (vacíos si no están)."""
    datos = {"nombre": "", "nif": "", "direccion": "", "iban": ""}
    if db is None:
        return datos
    try:
        from app.services.settings_service import get_runtime_str
        for clave, ajuste in (("nombre", "INVOICE_ISSUER_NAME"), ("nif", "INVOICE_ISSUER_TAX_ID"),
                              ("direccion", "INVOICE_ISSUER_ADDRESS"), ("iban", "INVOICE_ISSUER_IBAN")):
            datos[clave] = (get_runtime_str(db, ajuste, org_id) or "").strip()
    except Exception:
        logger.warning("invoice_pdf: datos del emisor no legibles", exc_info=True)
    return datos


def _bloque_de_cliente(client_name, client_address, client_vat, client_email,
                       est: dict, paleta) -> list:
    salida = [
        Paragraph(est["et"]["cliente"], est["etiqueta"]),
        Paragraph(_esc(client_name or "—"), est["nombre_cliente"]),
    ]
    if client_address:
        salida.append(Paragraph(_esc(client_address), est["cuerpo"]))
    if client_vat:
        salida.append(Paragraph(f"{est['et']['nif']}: {_esc(client_vat)}", est["pequeno"]))
    if client_email:
        salida.append(Paragraph(f"{est['et']['email']}: {_esc(client_email)}", est["pequeno"]))
    salida.append(HRFlowable(
        width="100%", thickness=0.5, color=paleta.color("linea_separadora"),
        spaceAfter=12, spaceBefore=12,
    ))
    return salida


def _tabla_de_lineas(lines: list, currency: str, subtotal, tax_rate, tax_amount,
                     total, est: dict, paleta) -> list:
    """Las lineas de la factura y sus totales, en una sola tabla.

    Van juntas a proposito: los totales tienen que quedar pegados a las lineas
    que suman, y `NOSPLIT` impide que un salto de pagina los separe — una
    factura con el total en una hoja aparte es una factura que nadie firma.
    """
    PS = est["PS"]
    principal = paleta.color("texto_principal")
    secundario = paleta.color("texto_secundario")

    def cabecera(texto, alineacion=None):
        kw = {"fontSize": 9, "fontName": est["fb"],
              "textColor": paleta.color("texto_sobre_cabecera")}
        if alineacion is not None:
            kw["alignment"] = alineacion
        return Paragraph(texto, PS("TH", **kw))

    def derecha(texto, fs=9, negrita=False):
        return Paragraph(str(texto), PS(
            "R", fontSize=fs,
            fontName=est["fb"] if negrita else est["fn"],
            textColor=principal, alignment=TA_RIGHT,
        ))

    def centrado(texto):
        return Paragraph(str(texto), PS(
            "C", fontSize=9, fontName=est["fn"],
            textColor=secundario, alignment=TA_CENTER,
        ))

    et = est["et"]
    filas = [[
        cabecera(et["descripcion"]),
        cabecera(et["ud"], TA_CENTER),
        cabecera(et["cant"], TA_RIGHT),
        cabecera(et["precio"], TA_RIGHT),
        cabecera(et["importe"], TA_RIGHT),
    ]]

    for line in lines:
        filas.append([
            Paragraph(_esc(line.get("description", "")), PS(
                "LineDesc", fontSize=9, fontName=est["fn"],
                textColor=principal, leading=13,
            )),
            centrado(_esc(line.get("unit") or "h")),
            # `:g` quita los decimales sobrantes: «2» y no «2.0» (sin cantidad, 1).
            derecha(f"{float(line.get('quantity') if line.get('quantity') is not None else 1):g}"
                    + (f" (-{float(line['discount_pct']):g}%)" if line.get("discount_pct") else "")),
            derecha(_importe(line.get("unit_price", 0), currency)),
            derecha(_importe(line.get("amount", 0), currency), negrita=True),
        ])

    def fila_de_total(etiqueta, valor, negrita=False):
        # La etiqueta ocupa las cuatro primeras columnas (SPAN abajo), alineada a
        # la derecha, para que el total quede bajo la columna de importes. En la
        # columna de precio (2 cm) sola, «IVA (20%):» se partía en dos líneas.
        return [Paragraph(etiqueta, PS(
            "TLbl", fontSize=9,
            fontName=est["fb"] if negrita else est["fn"],
            textColor=principal, alignment=TA_RIGHT,
        )), "", "", "", Paragraph(valor, PS(
            "TVal", fontSize=10 if negrita else 9,
            fontName=est["fb"] if negrita else est["fn"],
            textColor=principal, alignment=TA_RIGHT,
        ))]

    filas.append(fila_de_total(et["subtotal"], _importe(subtotal, currency)))
    # `:g` y no `:.0f`: un IVA del 7,5 % salía como «8 %».
    filas.append(fila_de_total(f"{_esc(est['impuesto'])} ({float(tax_rate or 0):g}%):", _importe(tax_amount, currency)))
    filas.append(fila_de_total(et["total"], _importe(total, currency), negrita=True))

    n = len(lines)
    tabla = Table(filas, colWidths=[9.5 * cm, 1.5 * cm, 1.5 * cm, 2 * cm, 2.5 * cm],
                  repeatRows=1)
    tabla.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), paleta.color("fondo_de_cabecera")),
        ("TEXTCOLOR", (0, 0), (-1, 0), paleta.color("texto_sobre_cabecera")),
        ("ROWBACKGROUNDS", (0, 1), (-1, n), [colors.white, paleta.color("fila_alterna")]),
        ("GRID", (0, 0), (-1, n), 0.3, paleta.color("borde_de_tabla")),
        ("LINEBELOW", (0, 0), (-1, 0), 1, paleta.color("acento")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("SPAN", (0, n + 1), (3, n + 1)),
        ("SPAN", (0, n + 2), (3, n + 2)),
        ("SPAN", (0, n + 3), (3, n + 3)),
        # Separador antes del subtotal.
        ("LINEABOVE", (0, n + 1), (-1, n + 1), 0.8, secundario),
        # La fila del TOTAL, destacada.
        ("BACKGROUND", (0, n + 3), (-1, n + 3), paleta.color("fila_de_total")),
        ("LINEBELOW", (0, n + 3), (-1, n + 3), 1.5, paleta.color("exito")),
        ("FONTSIZE", (0, n + 3), (-1, n + 3), 11),
        # NOSPLIT SOLO sobre el bloque de totales, no sobre la tabla entera.
        #
        # Antes era `(0, 0), (-1, -1)`, es decir: prohibido cualquier salto de
        # pagina en la tabla. Y como la tabla lleva las lineas dentro, eso
        # significaba que una factura mas alta que una pagina NO SE PODIA
        # GENERAR: ReportLab lanzaba `LayoutError` y el endpoint devolvia un
        # 500. Medido: hasta 29 lineas salia, con 30 fallaba.
        #
        # Una factura mensual de tiempo y materiales con treinta conceptos —una
        # linea por persona y proyecto— es lo normal, asi que el fallo estaba al
        # alcance de cualquier cliente mediano.
        #
        # Acotarlo al bloque de totales conserva la intencion original —que el
        # subtotal, el IVA y el TOTAL no se separen entre si ni queden solos en
        # una hoja— y deja que el cuerpo de lineas se reparta entre paginas,
        # que es para lo que existe `repeatRows=1`.
        ("NOSPLIT", (0, n + 1), (-1, n + 3)),
    ]))
    return [tabla]


def _bloque_de_notas(notes, est: dict, paleta) -> list:
    if not notes:
        return []
    return [
        Spacer(1, 16),
        HRFlowable(width="100%", thickness=0.5,
                   color=paleta.color("linea_separadora"), spaceAfter=8),
        Paragraph(est["et"]["notas"], est["etiqueta"]),
        Paragraph(_esc(notes), est["nota"]),
    ]


def _pie_de_factura(generated_by: str, invoice_number: str, est: dict, paleta,
                    generado_el: Optional[str] = None) -> list:
    from app.services.formato_regional import formatear_fecha
    # Baja (auditoría 22-11-2026): la hora en la zona de la empresa (`timeutil.now_local`),
    # no la del servidor.
    from app.core import timeutil
    cuando = generado_el or formatear_fecha(timeutil.now_local(), est["idioma"], con_hora=True)
    return [
        Spacer(1, 20),
        HRFlowable(width="100%", thickness=0.5, color=paleta.color("acento"), spaceAfter=6),
        Paragraph(
            _esc(f"{est['et']['generado'].format(quien=generated_by)} · {cuando} · {invoice_number}"),
            est["pie"],
        ),
    ]


def generate_invoice_pdf(
    invoice_number: str,
    issue_date,
    due_date,
    client_name: str,
    client_address: Optional[str],
    client_vat: Optional[str],
    client_email: Optional[str],
    lines: List[dict],
    subtotal: float,
    tax_rate: float,
    tax_amount: float,
    total: float,
    currency: Optional[str] = None,
    notes: Optional[str] = None,
    po_reference: Optional[str] = None,
    period_from=None,
    period_to=None,
    company_name: str = NOMBRE_COMPLETO_DEL_PRODUCTO,
    generated_by: str = NOMBRE_DEL_PRODUCTO,
    paleta=None,
    simbolo: Optional[str] = None,
    idioma: Optional[str] = None,
    nombre_de_impuesto: Optional[str] = None,
    generado_el: Optional[str] = None,
    emisor: Optional[dict] = None,
) -> bytes:
    """
    Genera un PDF de factura y devuelve los bytes en formato PDF.

    18-11-2026: `idioma` (etiquetas y formato de fecha; castellano si no se da),
    `nombre_de_impuesto` (si no, el habitual del idioma) y `generado_el` (la
    hora del pie ya formateada en la zona de la empresa; si no, la del servidor).
    """
    currency = currency or settings.DEFAULT_CURRENCY
    # El símbolo lo resuelve quien llama con el ajuste de su empresa
    # (`settings_service.simbolos_de_moneda(db, org)`); sin él, el ajuste global.
    if simbolo is None:
        from app.services.settings_service import simbolos_de_moneda
        simbolo = simbolos_de_moneda().get(str(currency).upper(), currency)
    # `paleta` la resuelve el llamador con `marca_de_organizacion()`, que es
    # quien tiene el `db` y el `organization_id`. Sin ella se usa la de
    # producto: los trabajos de fondo y los tests no tienen por que saber de
    # marca blanca.
    paleta = paleta or PALETA_DE_FACTURA
    est = _estilos_de_factura(paleta, idioma)
    est["idioma"] = idioma or IDIOMA_DE_RESPALDO
    est["et"] = etiquetas(est["idioma"])
    est["impuesto"] = nombre_de_impuesto or est["et"]["impuesto"]

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2.2 * cm, rightMargin=2.2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm,
    )

    elements = (
        _cabecera_de_factura(company_name, est, paleta)
        + _metadatos(invoice_number, issue_date, due_date, po_reference,
                     period_from, period_to, est)
        + _bloque_de_emisor(emisor, est)
        + _bloque_de_cliente(client_name, client_address, client_vat,
                             client_email, est, paleta)
        + _tabla_de_lineas(lines, simbolo, subtotal, tax_rate, tax_amount,
                           total, est, paleta)
        + _bloque_de_notas(notes, est, paleta)
        + _pie_de_factura(generated_by, invoice_number, est, paleta, generado_el)
    )

    doc.build(elements)
    return buffer.getvalue()


def pdf_de_factura(db, inv, lineas=None, *, org_id=None, company_name: str = NOMBRE_COMPLETO_DEL_PRODUCTO,
                   paleta=None, generated_by: str = NOMBRE_DEL_PRODUCTO) -> bytes:
    """El PDF de una `Invoice` guardada: la unica traduccion fila → `generate_invoice_pdf`.

    Auditoria 2026-11 (hallazgo 23). La misma traduccion (lineas, moneda y su
    simbolo, datos fiscales) estaba copiada en `GET /invoices/{id}/pdf` y en
    `GET /billing-reports/invoices/{id}/pdf`, y `POST /pdf/export` con
    `export_type=invoice` tenia ademas su propio dibujo de factura, sin NIF ni
    direccion y con `€` fijo. Los tres pasan ahora por aqui.

    18-11-2026: en el idioma del cliente (o de la empresa), con el impuesto y
    la moneda de la empresa y la hora del pie en su zona horaria.
    """
    from app.services.formato_regional import codigo_de_moneda, sello_de_hora, simbolo_de_moneda

    if lineas is None:
        lineas = sorted(inv.lines or [], key=lambda x: (x.order or 0))
    org = org_id if org_id is not None else getattr(inv, "organization_id", None)
    moneda = (getattr(inv, "currency", None) or codigo_de_moneda(db, org)).upper()
    idioma = idioma_de_la_factura(db, inv, org)
    return generate_invoice_pdf(
        simbolo=simbolo_de_moneda(db, org, moneda=moneda),
        idioma=idioma,
        nombre_de_impuesto=nombre_del_impuesto(db, org, idioma),
        generado_el=sello_de_hora(db, org, idioma),
        emisor=datos_del_emisor(db, org),
        invoice_number=inv.number,
        issue_date=inv.issue_date,
        due_date=inv.due_date,
        client_name=inv.client_name or "",
        client_address=inv.client_address,
        client_vat=inv.client_vat,
        client_email=inv.client_email,
        lines=[
            {
                "description": ln.description,
                "unit": ln.unit,
                "quantity": ln.quantity,
                "unit_price": ln.unit_price,
                "amount": ln.amount,
                "discount_pct": ln.discount_pct,
            }
            for ln in lineas
        ],
        subtotal=inv.subtotal or 0,
        tax_rate=inv.tax_rate or 0,
        tax_amount=inv.tax_amount or 0,
        total=inv.total or 0,
        currency=moneda,
        notes=inv.notes,
        po_reference=inv.po_reference,
        period_from=inv.period_from,
        period_to=inv.period_to,
        company_name=company_name,
        paleta=paleta,
        generated_by=generated_by,
    )
